export function sanitizeLanguage(value) {
  return SUPPORTED_LANGUAGES.some((lang) => lang.id === value) ? value : DEFAULT_LANGUAGE;
}

export function getLanguage() {
  return sanitizeLanguage(settings.language);
}

export function getLocale() {
  return SUPPORTED_LANGUAGES.find((lang) => lang.id === getLanguage())?.locale || "en";
}

export function t(key, vars = {}) {
  const lang = getLanguage();
  const table = messages[lang] || messages.en;
  let text = table[key] ?? messages.en[key] ?? key;

  Object.entries(vars).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });

  return text;
}

export function getHomeWidgetLabel(widgetId) {
  if (widgetId === "weekly") return t("home.widgetWeekly");
  if (widgetId === "routines") return t("home.widgetRoutines");
  return widgetId;
}

export function applyDocumentLanguage() {
  const lang = getLanguage();
  document.documentElement.lang = getLocale();

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (!key) return;
    node.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (!key) return;
    node.setAttribute("aria-label", t(key));
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (!key) return;
    node.setAttribute("placeholder", t(key));
  });
}
